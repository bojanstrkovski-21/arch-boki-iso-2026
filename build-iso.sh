#!/usr/bin/env bash
echo "###################################################################"
echo "###########           Archknife ISO builder!           ############"
echo "###################################################################"
sleep 2

echo "###################################################################"
echo "###########    Cleaning Leftovers from older builds!    ###########"
echo "###################################################################"

sudo rm -rf work/*
rm -rf out/*
rm build.log

sleep 3

echo "###################################################################"
echo "###########              Buiding the ISO!              ############"
echo "###################################################################"

sleep 3

sudo mkarchiso -v -w work/ -o out/ iso/ 2>&1 | tee build.log

echo "###################################################################"
echo "###########               Build finished!              ############"
echo "###################################################################"

ls -alh out